from __future__ import annotations

import logging
import os
import shutil
import subprocess

from app.modules.mitigation.interfaces import RuleWriter

logger = logging.getLogger(__name__)


class NginxRuleWriter(RuleWriter):
    """
    Writes IP blocklist and rate-limit configuration to the Nginx includes
    directory and signals Nginx to reload.
    """

    def __init__(self, blocklist_path: str) -> None:
        self._blocklist_path = blocklist_path
        parent_dir = os.path.dirname(blocklist_path) or "."
        self._rate_limit_path = os.path.join(parent_dir, "rate_limits.conf")

    def write_blocklist(self, ips: list[str]) -> None:
        """Overwrite the Nginx blocklist file with 'deny <ip>;' directives."""
        parent = os.path.dirname(self._blocklist_path)
        if parent:
            os.makedirs(parent, exist_ok=True)

        lines = ["# Auto-generated by CLOUDSHIELD Mitigation Module\n"]
        for ip in sorted(set(ips)):
            lines.append(f"deny {ip};\n")

        with open(self._blocklist_path, "w", encoding="utf-8") as f:
            f.writelines(lines)

    def write_rate_limits(self, rules: list[dict]) -> None:
        """Write Nginx rate-limit directives for given IPs/endpoints."""
        parent = os.path.dirname(self._rate_limit_path)
        if parent:
            os.makedirs(parent, exist_ok=True)

        lines = ["# Auto-generated rate-limit rules by CLOUDSHIELD\n"]
        for rule in rules:
            target = rule.get("target", "")
            rate = rule.get("rate", 10)
            burst = rule.get("burst", 20)
            lines.append(f"# target={target} rate={rate}r/s burst={burst}\n")
            if target.startswith("/"):
                lines.append(
                    f"location {target} {{ limit_req zone=cloudshield_zone burst={burst} nodelay; }}\n"
                )

        with open(self._rate_limit_path, "w", encoding="utf-8") as f:
            f.writelines(lines)

    def reload(self) -> None:
        """Signal Nginx to reload its configuration without dropping connections."""
        if shutil.which("nginx") is None:
            logger.debug("nginx binary not found on PATH; skipping reload.")
            return

        try:
            subprocess.run(["nginx", "-s", "reload"], check=True, capture_output=True, text=True)
        except subprocess.SubprocessError as exc:
            logger.warning("Failed to reload nginx: %s", exc)