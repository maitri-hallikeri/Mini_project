import asyncio
import os
from contextlib import asynccontextmanager
from typing import List
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware

from app.config import settings
from app.schemas import (
    DetectionAlert,
    MitigationRecord,
    ContainerHealthRecord,
    ProtectionAction,
)
from app.mitigation import mitigation_manager
from app.recovery import recovery_manager

# File shared with Person 3's Nginx reverse proxy
NGINX_BLOCKLIST_PATH = os.path.join(os.path.dirname(__file__), "..", "nginx_blocked_ips.conf")


def sync_nginx_blocklist() -> None:
    """
    Writes currently active TEMPORARY_BLOCK IPs into an Nginx-compatible
    config file so Person 3's Nginx proxy enforces blocks automatically.
    """
    active = mitigation_manager.get_active_restrictions()
    blocked_ips = [
        r.source_ip for r in active if r.action_taken == ProtectionAction.TEMPORARY_BLOCK
    ]

    lines = ["# Auto-generated by CLOUDSHIELD Protection Engine (Person 2)\n"]
    for ip in blocked_ips:
        lines.append(f"deny {ip};\n")

    with open(NGINX_BLOCKLIST_PATH, "w", encoding="utf-8") as f:
        f.writelines(lines)


async def background_monitor_loop():
    """
    Runs continuously in the background every 5 seconds:
    1. Cleans up expired IP blocks and updates Nginx blocklist.
    2. Checks container health and triggers automated Docker recovery if needed.
    """
    while True:
        try:
            expired = mitigation_manager.cleanup_expired_restrictions()
            if expired:
                sync_nginx_blocklist()

            recovery_manager.check_and_recover_all()
        except Exception as e:
            print(f"[Monitor Loop Warning]: {e}")

        await asyncio.sleep(settings.HEALTH_CHECK_INTERVAL_SECONDS)


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Startup: Initialize empty Nginx blocklist & start background health monitor
    sync_nginx_blocklist()
    monitor_task = asyncio.create_task(background_monitor_loop())
    yield
    # Shutdown: Cancel background loop cleanly
    monitor_task.cancel()


app = FastAPI(
    title=settings.PROJECT_NAME,
    version=settings.VERSION,
    description="Automated DDoS Protection & Container Recovery Microservice (Person 2)",
    lifespan=lifespan,
)

# Enable CORS so Person 4's React Dashboard (localhost:5173 / 3000) can call these APIs
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# ==========================================
# 1. SYSTEM & INTEGRATION HEALTH ENDPOINTS
# ==========================================
@app.get("/")
def root():
    return {
        "service": settings.PROJECT_NAME,
        "status": "ONLINE",
        "docker_connected": recovery_manager.docker_available,
    }


# ==========================================
# 2. PROTECTION ENDPOINTS (Person 1 -> You)
# ==========================================
@app.post("/api/v1/mitigate", response_model=MitigationRecord)
def receive_detection_alert(alert: DetectionAlert):
    """
    Called by Person 1's Detection Module whenever suspicious traffic is detected.
    Evaluates risk, applies rate-limiting or temporary block, and updates Nginx rules.
    """
    decision = mitigation_manager.evaluate_and_mitigate(alert)
    sync_nginx_blocklist()
    return decision


@app.get("/api/v1/mitigations/active", response_model=List[MitigationRecord])
def list_active_mitigations():
    """Called by Person 4's Dashboard to display currently blocked/limited IPs."""
    return mitigation_manager.get_active_restrictions()


@app.get("/api/v1/mitigations/history", response_model=List[MitigationRecord])
def list_mitigation_history():
    """Called by Person 4's Dashboard to display full incident audit logs."""
    return mitigation_manager.mitigation_history


@app.delete("/api/v1/mitigations/{ip_address}")
def manual_unblock_ip(ip_address: str):
    """Allows an admin on the dashboard to manually unblock an IP early."""
    removed = mitigation_manager.manual_unblock(ip_address)
    if not removed:
        raise HTTPException(status_code=404, detail=f"IP {ip_address} is not currently restricted.")
    sync_nginx_blocklist()
    return {"status": "UNBLOCKED", "ip_address": ip_address}


# ==========================================
# 3. RECOVERY ENDPOINTS (You -> Person 3 & 4)
# ==========================================
@app.get("/api/v1/recovery/status", response_model=List[ContainerHealthRecord])
def get_containers_health():
    """Returns real-time health status of all monitored application containers."""
    if not recovery_manager.container_statuses:
        return recovery_manager.check_and_recover_all()
    return list(recovery_manager.container_statuses.values())


@app.get("/api/v1/recovery/history")
def get_recovery_history():
    """Returns audit logs of past automated container restarts and recovery times."""
    return recovery_manager.recovery_history


@app.post("/api/v1/recovery/simulate-crash/{container_name}")
def simulate_container_crash(container_name: str):
    """
    Helper endpoint for local demos/testing: marks a container as crashed
    so you can watch the background monitor heal it within ~15 seconds.
    """
    if container_name not in settings.TARGET_CONTAINERS:
        raise HTTPException(status_code=404, detail="Unknown container name.")
    recovery_manager.simulated_unhealthy.add(container_name)
    return {
        "message": f"Simulated crash injected for '{container_name}'. Background monitor will recover it after {settings.FAILURE_THRESHOLD} failed checks."
    }